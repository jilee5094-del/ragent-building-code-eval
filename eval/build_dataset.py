def norm(s):
    return re.sub(r'\s+', '', s).replace('m²', 'm2')


def main():
    rows, errors = [], []
    for i, (typ, q, gold, points) in enumerate(Q, 1):
        for g in gold:
            if g not in CLAUSES:
                errors.append(f'Q{i:02d} 标准条文不存在: {g}')
        text = norm(''.join(CLAUSES[g]['text'] for g in gold if g in CLAUSES))
        for p in points:
            if norm(p) not in text:
                errors.append(f'Q{i:02d} 答案要点“{p}”不在标准条文 {gold} 原文中')
        rows.append({'id': f'Q{i:02d}', 'type': typ, 'question': q,
                     'gold_clauses': [f'GB50096-2011:{g}' for g in gold], 'answer_points': points,
                     'answerable': bool(gold)})
    if errors:
        raise SystemExit('评测集自检失败:\n' + '\n'.join(errors))
    with io.open(os.path.join(HERE, 'gb50096_eval.jsonl'), 'w', encoding='utf-8') as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + '\n')
    from collections import Counter
    print('题目', len(rows), dict(Counter(r['type'] for r in rows)), '自检通过')


if __name__ == '__main__':
    main()
